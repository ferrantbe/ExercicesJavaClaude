package be.ephec.java.itf.e01;

/**
 * ITF.1 — Cette interface vous est FOURNIE, comme modele.
 *
 * Observez ce qu'elle contient : une signature, un point-virgule, et rien
 * d'autre. Pas de corps, pas de champ. Elle ne dit pas COMMENT on calcule,
 * seulement qu'on peut calculer.
 *
 * Notez aussi ce qu'on n'ecrit pas : ni public, ni abstract. Dans une
 * interface, une methode est implicitement les deux.
 */
public interface Calculateur {

    int calcule(int a, int b);
}
