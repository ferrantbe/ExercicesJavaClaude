package be.ephec.java.tab.e04;

/** TAB.4 — Cette classe vous est FOURNIE. */
public class Person {

    private final String nom;
    private final String prenom;

    public Person(String nom, String prenom) {
        this.nom = nom;
        this.prenom = prenom;
    }

    public String getNom() {
        return nom;
    }

    public String getPrenom() {
        return prenom;
    }
}
